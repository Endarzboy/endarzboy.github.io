#!/usr/bin/env python3
"""Regenerate the CV page's full publication list from your CV bibliography.

Usage:
  python3 tools/bib2cv.py my_CV_latex/cv_publications.bib

Writes _data/cv_publications.yml, which the CV page (/cv/) reads.
Uses the `keywords` field of each entry as its status:
  published | accepted | acceptedchapter | underrevision | submitted | inpreparation
Only published and accepted work is shown: entries marked `underrevision`,
`submitted` or `inpreparation` are skipped (never shown publicly).
Entries are written newest year first (accepted items without a year come first).
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bib2yml import parse_entries, names  # noqa: E402

STATUS = {
    "published": "published", "accepted": "accepted", "acceptedchapter": "chapter",
    "underrevision": None, "submitted": None, "inpreparation": None,
}
MAX_AUTHORS = 10


def clean_title(t):
    return t.replace("--", "–").strip()


def author_list(field):
    auth = [re.sub(r"\s+", " ", a).strip() for a in names(field)] if field else []
    if len(auth) <= MAX_AUTHORS:
        return auth
    mine = [a for a in auth if "Maregu" in a]
    return auth[:3] + (["…"] + mine if mine and mine[0] not in auth[:3] else []) + ["et al."]


def venue_of(f, status):
    if status == "review":
        return ""
    v = f.get("journal") or f.get("booktitle") or ""
    if f.get("note") and not v:
        v = re.split(r"[,.]", f["note"].replace("Accepted, ", ""), maxsplit=1)[0] if status == "accepted" else ""
    if status == "accepted" and f.get("note"):
        v = f["note"].replace("Accepted, ", "").replace(" (poster)", "")
    extra = []
    if f.get("volume"):
        extra.append(f["volume"] + (f"({f['number']})" if f.get("number") else ""))
    if f.get("pages"):
        pg = f["pages"].replace("--", "–")
        extra.append(("pp. " + pg) if "–" in pg or "-" in pg else ("Art. " + pg))
    return v + (", " + ", ".join(extra) if extra else "")


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    entries = parse_entries(src.read_text(encoding="utf-8"))
    out = ["# Generated by tools/bib2cv.py from " + src.name + " — edit the .bib and re-run, or edit here.",
           "# status: published | accepted | chapter. Ordered newest first."]
    n = 0
    def year_of(e):
        y = re.sub(r"\D", "", e[2].get("year", ""))
        return int(y) if y else 9999
    entries = sorted(entries, key=year_of, reverse=True)  # stable: keeps .bib order within a year
    for etype, key, f, _raw in entries:
        status = STATUS.get(f.get("keywords", "published").split(",")[0].strip().lower(), "published")
        if status is None:
            continue
        note = f.get("note", "")
        equal = "contributed equally" in note
        link = ""
        if f.get("doi"):
            link = "https://doi.org/" + f["doi"]
        elif f.get("url") and status != "review":
            link = f["url"]
        year = re.sub(r"\D", "", f.get("year", "")) or ""
        out += [
            f"- key: {key}",
            f"  title: {q(clean_title(f.get('title', '')))}",
            "  authors: [" + ", ".join(q(a) for a in author_list(f.get("author", ""))) + "]",
            f"  venue: {q(venue_of(f, status))}",
            f"  year: {q(year)}",
            f"  status: {status}",
        ]
        if equal:
            out.append("  equal: true")
        if link:
            out.append(f"  link: {link}")
        n += 1
    dest = Path(__file__).resolve().parent.parent / "_data" / "cv_publications.yml"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {n} entries to {dest}")


if __name__ == "__main__":
    main()
